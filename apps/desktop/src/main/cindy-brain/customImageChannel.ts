/**
 * Standalone OpenAI Images for user connections. The model's sourceAgent owns
 * its endpoint, encrypted key and headers; chat compatibility alone never opts
 * a connection into media. No supplier names or proxy-specific adapters.
 */
import { isLoopbackProviderUrl, type AgentKind, type Provider } from '@cindy/model-providers';
import { normalizeImageParameters } from '../cindy-media/imageParameters.js';
import {
  createGatewayImageClient,
  type CreateGatewayImageClientOptions,
} from '../cindy-proxy-media/api/gatewayImageClient.js';
import type { ImageChannel, ImageChannelRegistry } from './imageChannelRegistry.js';

interface CustomImageConnection {
  agent: AgentKind;
  baseUrl: string;
  headers: Record<string, string>;
}

export interface CustomImageChannelOptions {
  getProvider(): Provider | undefined;
  readApiKey(agent: AgentKind): string | null;
  getOwnerScopeKey(): string;
  isOwnerBoundaryPending(): boolean;
  fetchImplementation: typeof fetch;
  beforeDispatch(model: string): void;
  logger?: CreateGatewayImageClientOptions['logger'];
}

/** Preserve gateway path prefixes, accepting either an API origin or a /v1 base. */
function imagesBaseUrl(raw: string): string | null {
  try {
    const url = new URL(raw);
    if (
      !['http:', 'https:'].includes(url.protocol) ||
      url.username ||
      url.password ||
      url.search ||
      url.hash
    )
      return null;
    const path = url.pathname.replace(/\/+$/, '');
    url.pathname = path.endsWith('/v1') ? path : `${path}/v1`;
    return url.toString().replace(/\/+$/, '');
  } catch {
    return null;
  }
}

/** Explicit API-key/loopback connections only; native subscription auth stays in its channel. */
export function isCustomImageProvider(provider: Provider): boolean {
  return (
    provider.source === 'user' &&
    !provider.auth.native &&
    (provider.auth.method === 'apiKey' || provider.auth.method === 'none') &&
    (provider.imageModels?.length ?? 0) > 0 &&
    Object.values(provider.routing).some((route) => route?.imageApi === 'openai-images')
  );
}

function connectionForModel(
  opts: CustomImageChannelOptions,
  modelId: string,
): CustomImageConnection | null {
  const provider = opts.getProvider();
  if (opts.isOwnerBoundaryPending() || !provider || !isCustomImageProvider(provider)) return null;
  const media = provider.imageModels?.find((model) => model.id === modelId);
  // Never borrow another runtime's credentials when the model's own route is missing.
  const agent = media?.sourceAgent;
  if (!agent) return null;
  const route = provider.routing[agent];
  const model = provider.models[agent]?.find((model) => model.id === modelId);
  if (
    !route ||
    route.disabled ||
    route.imageApi !== 'openai-images' ||
    !model ||
    route.headerOverrideState === 'unknown'
  )
    return null;
  const upstream = model.route?.baseUrl ?? route.upstream;
  const baseUrl = imagesBaseUrl(upstream);
  if (!baseUrl || !imagesBaseUrl(route.upstream)) return null;
  // Model overrides must stay within the credential owner's origin.
  if (new URL(upstream).origin !== new URL(route.upstream).origin) return null;
  const headers: Record<string, string> = {};
  for (const [name, value] of Object.entries(route.headerOverride ?? {})) {
    // Authentication belongs to this connection. Multipart boundaries, host and
    // body length are generated by fetch, never inherited from chat headers.
    const lower = name.toLowerCase();
    if (
      [
        'authorization',
        'x-api-key',
        'api-key',
        'cookie',
        'host',
        'content-type',
        'content-length',
        'connection',
        'chatgpt-account-id',
        'openai-account-id',
        'openai-beta',
        'originator',
        'session_id',
      ].includes(lower)
    )
      continue;
    headers[lower] = value;
  }
  for (const name of route.headerDelete ?? []) delete headers[name.toLowerCase()];
  if (provider.auth.method === 'none') {
    if (route.authStrategy !== 'none' || !isLoopbackProviderUrl(baseUrl)) return null;
  } else {
    if (route.authStrategy !== 'api-key-header') return null;
    const key = opts.readApiKey(agent)?.trim();
    if (!key) return null;
    headers.authorization = `Bearer ${key}`;
  }
  return { agent, baseUrl, headers };
}

export function createCustomImageChannel(opts: CustomImageChannelOptions): ImageChannel {
  const connection = (model: string) => connectionForModel(opts, model);
  const ready = () =>
    !opts.isOwnerBoundaryPending() &&
    (opts.getProvider()?.imageModels ?? []).some((model) => connection(model.id) !== null);

  const invoke = async (
    operation: 'generate' | 'edit',
    params: Parameters<ImageChannel['editImage']>[0],
  ) => {
    const owner = opts.getOwnerScopeKey();
    const binding = connection(params.model);
    if (!binding) throw new Error('所选图像来源的 OpenAI Images 接口或凭证未就绪');
    const assertOwner = () => {
      if (opts.isOwnerBoundaryPending() || owner !== opts.getOwnerScopeKey()) {
        throw new Error('图像请求期间账号已切换，本次操作已取消');
      }
    };
    const client = createGatewayImageClient({
      getApiKey: () => null,
      getRequestHeaders: () => binding.headers,
      proxy: {
        baseUrl: binding.baseUrl,
        generatePath: '/images/generations',
        editPath: '/images/edits',
      },
      brandLabel: opts.getProvider()?.name,
      logger: opts.logger,
      // Custom credential headers must never follow a redirect to another endpoint.
      fetchImplementation: (url, init) => {
        assertOwner();
        return opts.fetchImplementation(url, { ...init, redirect: 'error' });
      },
      beforeDispatch: () => {
        assertOwner();
        params.signal?.throwIfAborted();
        const current = connection(params.model);
        if (
          !current ||
          current.agent !== binding.agent ||
          current.baseUrl !== binding.baseUrl ||
          JSON.stringify(current.headers) !== JSON.stringify(binding.headers)
        ) {
          throw new Error('图像来源配置已变化，本次请求未发出');
        }
        opts.beforeDispatch(params.model);
      },
    });
    const normalized = normalizeImageParameters('openai', params.model, params);
    const input = { model: params.model, prompt: params.prompt, ...normalized };
    const result =
      operation === 'edit'
        ? await client.editImage({ ...input, imagePaths: params.imagePaths }, params.signal)
        : await client.generateImage(input, params.signal);
    assertOwner();
    return result;
  };

  return {
    imageProtocol: 'openai',
    ready,
    isModelReady: (model) => connection(model) !== null,
    generateImage: (params) => invoke('generate', { ...params, imagePaths: [] }),
    editImage: (params) => invoke('edit', params),
  };
}

/** Synchronize user connections without overwriting built-in or native subscription channels. */
export function registerCustomImageChannels(
  registry: ImageChannelRegistry,
  providers: readonly Provider[],
  registered: Set<string>,
  createChannel: (providerId: string) => ImageChannel,
): void {
  for (const provider of providers) {
    if (
      !isCustomImageProvider(provider) ||
      registered.has(provider.id) ||
      registry.hasProvider(provider.id)
    )
      continue;
    registry.register(provider.id, createChannel(provider.id));
    registered.add(provider.id);
  }
}
